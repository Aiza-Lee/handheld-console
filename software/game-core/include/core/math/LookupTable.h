// sin(2*pi*phase/256) * scale / 128  (phase in [0,255], scale = amplitude)
inline int16_t sin_lut(uint8_t phase, int16_t scale) {
    return static_cast<int16_t>(SIN_LUT[phase]) * scale / 128;
}

// cos(2*pi*phase/256) * scale / 128  (cos = sin shifted by 64 = 90 degrees)
inline int16_t cos_lut(uint8_t phase, int16_t scale) {
    return sin_lut(static_cast<uint8_t>(phase + 64U), scale);
}

